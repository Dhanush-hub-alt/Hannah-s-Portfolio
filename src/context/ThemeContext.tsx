"use client";

import React, { createContext, useContext, useEffect, useState } from "react";

type Theme = "dark" | "light";

interface ThemeContextType {
  theme: Theme;
  toggleTheme: () => void;
  setTheme: (theme: Theme) => void;
}

const ThemeContext = createContext<ThemeContextType>({
  theme: "light",
  toggleTheme: () => {},
  setTheme: () => {},
});

export function ThemeProvider({ children }: { children: React.ReactNode }) {
  const [theme, setThemeState] = useState<Theme>("light");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setMounted(true);
    // When the user opens the application, ensure it defaults to light theme.
    // If the user manually toggles within their active session, we honor that in sessionStorage,
    // but a fresh open / default load always starts in light theme.
    const sessionTheme = sessionStorage.getItem("hannah_portfolio_theme") as Theme | null;
    if (sessionTheme === "dark") {
      setThemeState("dark");
      applyTheme("dark");
    } else {
      setThemeState("light");
      applyTheme("light");
      sessionStorage.setItem("hannah_portfolio_theme", "light");
      localStorage.setItem("hannah_portfolio_theme", "light");
    }
  }, []);

  const applyTheme = (t: Theme) => {
    const root = document.documentElement;
    if (t === "dark") {
      root.classList.add("dark");
      root.classList.remove("light");
      root.setAttribute("data-theme", "dark");
    } else {
      root.classList.remove("dark");
      root.classList.add("light");
      root.setAttribute("data-theme", "light");
    }
  };

  const setTheme = (newTheme: Theme) => {
    setThemeState(newTheme);
    sessionStorage.setItem("hannah_portfolio_theme", newTheme);
    localStorage.setItem("hannah_portfolio_theme", newTheme);
    applyTheme(newTheme);
  };

  const toggleTheme = () => {
    const next = theme === "dark" ? "light" : "dark";
    setTheme(next);
  };

  return (
    <ThemeContext.Provider value={{ theme, toggleTheme, setTheme }}>
      {children}
    </ThemeContext.Provider>
  );
}

export const useTheme = () => useContext(ThemeContext);
